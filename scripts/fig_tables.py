def md_rows(path, header_start):
    pass
    lines = [ln.strip() for ln in path.read_text().splitlines()]
    for i, ln in enumerate(lines):
        if ln.startswith(header_start):
            rows = []
            for ln2 in lines[i + 2:]:
                if not ln2.startswith("|"):
                    break
                rows.append([c.strip() for c in ln2.strip().strip("|").split("|")])
            return rows
    raise KeyError(f"{header_start!r} not found in {path}")

def disp(x, d):
    pass
    q = Decimal(repr(round(float(x), 10)))
    while q != 0 and d < 10 and q.quantize(Decimal(1).scaleb(-d), rounding=ROUND_HALF_UP) == 0:
        d += 1
    shifted = q.scaleb(d)
    if abs(shifted - int(shifted)) == Decimal("0.5"):
        d += 1
    return f"{q.quantize(Decimal(1).scaleb(-d), rounding=ROUND_HALF_UP):f}"

def pct(x, d=1, sign=False):
    pass
    q = Decimal(repr(round(float(x), 12))) * 100
    if q == 0:
        return "0"
    r = q.quantize(Decimal(1).scaleb(-d), rounding=ROUND_HALF_UP)
    if r == 0:
        return ("$-$" if q < 0 else "") + "$<$" + str(Decimal(1).scaleb(-d))
    out = f"{r:f}"
    if out.startswith("-"):
        out = "$-$" + out[1:]
    elif sign:
        out = "$+$" + out
    return out

def tex_num(s):
    pass
    s = s.strip()
    return f"${s}$" if s.startswith(("-", "+")) else s

