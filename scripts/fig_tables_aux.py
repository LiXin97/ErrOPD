def selection():
    pass
    sys.path.insert(0, str(REPO / "scripts"))
    import e1_selection as E
    cands, _ = E.load_candidates()
    cands = [r for r in cands if r["experiment"] != "DRYRUN"]
    G = E.groups(cands)
    out_rows = []
    for k, v in sorted(G.items(), key=lambda kv: kv[0]):
        contested = int(any(r["_parse"] < E.COLLAPSE for r in v) and any(r["_parse"] >= E.HEALTHY for r in v))
        for sel, key in (("a_parsed", "_nd"), ("c_repair", "_c"), ("c_repair8", "_c8"), ("b_useful", "_u")):
            pp = E.pick(v, key)
            if pp is None:
                continue
            pu = E.pick(v, "_u")
            out_rows.append({"group_kind": k[0], "group": " | ".join(k[1:]), "selector": sel, "contested": contested,
                             "pick_collapsed": int(pp["_parse"] < E.COLLAPSE), "pick_degraded": int(pp["_parse"] < E.DEGRADE),
                             "useful_regret": round((pu["_u"] or 0) - (pp["_u"] or 0), 4)})
    keep = lambda v: all(x["_rope"] == "false" for x in v)
    rb = E.random_baseline(G, out_rows, keep=keep)
    con = sorted(k for k, v in G.items() if any(r["_parse"] < E.COLLAPSE for r in v)
                 and any(r["_parse"] >= E.HEALTHY for r in v) and keep(v))
    per = {}
    for r in out_rows:
        k = tuple([r["group_kind"]] + r["group"].split(" | "))
        if r["selector"] == "c_repair8" and k in con:
            per[k] = r["pick_collapsed"]
    ks = [k for k in con if k in per]
    rng = random.Random(0)
    bs = sorted(sum(per[ks[rng.randrange(len(ks))]] for _ in ks) / len(ks) for _ in range(10000))
    rb["c_repair8"] = {"n": len(ks), "point": (sum(per[k] for k in ks) / len(ks),), "ci": [(bs[250], bs[9749])]}
    return rb, len(con)

def clopper_pearson(k, n, a=0.05):
    pass
    from math import comb
    def tail_ge(p):
        return sum(comb(n, j) * p ** j * (1 - p) ** (n - j) for j in range(k, n + 1))
    def tail_le(p):
        return sum(comb(n, j) * p ** j * (1 - p) ** (n - j) for j in range(0, k + 1))
    def solve(f, target, increasing):
        lo_, hi_ = 0.0, 1.0
        for _ in range(100):
            mid = (lo_ + hi_) / 2
            if (f(mid) < target) == increasing:
                lo_ = mid
            else:
                hi_ = mid
        return (lo_ + hi_) / 2
    lo = 0.0 if k == 0 else solve(tail_ge, a / 2, True)
    hi = 1.0 if k == n else solve(tail_le, a / 2, False)
    return lo, hi

def selection_ci(key, r):
    pass
    p, (lo, hi) = r["point"][0], r["ci"][0]
    k = round(p * r["n"])
    if key != "random" and abs(k - p * r["n"]) < 1e-9:
        lo, hi = clopper_pearson(k, r["n"])
    return lo, hi

def write_selection():
    rb, n = selection()
    names = [("a_parsed", "NDCG@1, parsed outputs"), ("c_repair", "NDCG@1 after repair"),
             ("c_repair8", "NDCG@8 after repair"), ("b_useful", "NDCG@1, invalid as 0"), ("random", "random pick")]
    L = ["% Generated by scripts/fig_tables_aux.py; do not edit by hand.",
         "% source: scripts/e1_selection.py (candidates, groups, pick rule, random baseline) on",
         "% results/ledger.csv, legacy_ledger.csv, E1_three_way.csv; groups in results/E1_groups.csv",
         "\\begin{table}[t]", "\\centering", "\\small",
         "\\begin{tabular}{@{}lc@{}}", "\\toprule", "selection metric & failing pick, \\% [95\\% CI] \\\\", "\\midrule"]
    for key, name in names:
        r = rb.get(key)
        if not r:
            continue
        p = r["point"][0]
        lo, hi = selection_ci(key, r)
        cell = f"{100 * p:.0f} [{100 * lo:.0f}, {100 * hi:.0f}]"
        if key == "a_parsed":
            cell = f"\\textbf{{{100 * p:.0f}}} [{100 * lo:.0f}, {100 * hi:.0f}]"
        L.append(f"{name} & {cell} \\\\ % groups: {r['n']}")
    L += ["\\bottomrule", "\\end{tabular}",
          f"\\caption{{Selecting on parseable outputs picks the failing checkpoint twice as often as chance (share of {n} "
          "contested groups, exact 95\\% CIs).}",
          "\\label{tab:selection}", "\\end{table}"]
    (OUT / "tab_selection.tex").write_text("\n".join(L) + "\n")
    return rb, n

