T975 = {1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776}

def mean_pm(v):
    pass
    v = [x for x in v if x is not None]
    if not v:
        return None, None
    return st.mean(v), (T975[len(v) - 1] * st.stdev(v) / len(v) ** 0.5 if len(v) > 1 else None)

